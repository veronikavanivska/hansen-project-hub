type I18nContextValue = { lang: Language; setLang: (lang: Language) => void; t: (text: string) => string };
const I18nContext = createContext<I18nContextValue>({ lang: "pl", setLang: () => {}, t: (text) => text });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>(() => (localStorage.getItem("hansen_lang") as Language) || "pl");
  useEffect(() => localStorage.setItem("hansen_lang", lang), [lang]);
  const value = useMemo(() => ({ lang, setLang, t: (text: string) => (lang === "pl" ? PL[text] ?? text : text) }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }

export function LanguageSwitch() {
  const { lang, setLang } = useI18n();
  return <div className="language-switch" aria-label="Language"><button className={lang === "pl" ? "active" : ""} onClick={() => setLang("pl")}>PL</button><button className={lang === "en" ? "active" : ""} onClick={() => setLang("en")}>EN</button></div>;
}
